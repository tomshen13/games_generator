#!/usr/bin/env node
/**
 * Pre-record every phrase Nikud Castle speaks with ElevenLabs.
 * Writes games/nikud-castle/audio/<hash>.mp3 and audio/clips.js ({ text → file }).
 * Only missing clips are generated; pass --force to re-record everything
 * (e.g. after changing VOICE_ID). Needs ELEVENLABS_API_KEY in .env.local.
 *
 *   node scripts/gen-nikud-audio.mjs [--force] [--dry-run] [--only "phrase" ...]
 *
 * --only re-records just the given phrases (copy them from audio/review.html).
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { tts } from './eleven.mjs';

const VOICE_ID = 'Tbj9UQjXon5RB9MPEyc2'; // Zina — young, warm Hebrew voice
const MODEL_ID = 'eleven_v4';
const CONCURRENCY = 3;

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const GAME_DIR = path.join(ROOT, 'games/nikud-castle');
const AUDIO_DIR = path.join(GAME_DIR, 'audio');
const MANIFEST = path.join(AUDIO_DIR, 'clips.js');
const force = process.argv.includes('--force');
const dryRun = process.argv.includes('--dry-run');
const only = process.argv.flatMap((a, i, all) => (all[i - 1] === '--only' ? [a.normalize('NFC')] : []));

// Load the game's data file to get the exact phrases it speaks
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(GAME_DIR, 'nikud-data.js'), 'utf8') + ';this.NikudData = NikudData;', ctx);
const phrases = ctx.NikudData.allPhrases();

fs.mkdirSync(AUDIO_DIR, { recursive: true });
const fileFor = text => crypto.createHash('sha1').update(`${VOICE_ID}|${MODEL_ID}|${text}`).digest('hex').slice(0, 12) + '.mp3';

const todo = only.length
  ? phrases.filter(t => only.includes(t.normalize('NFC')))
  : phrases.filter(t => force || !fs.existsSync(path.join(AUDIO_DIR, fileFor(t))));
if (only.length && todo.length < only.length) console.warn('Some --only phrases are not spoken by the game');
const chars = todo.reduce((n, t) => n + t.length, 0);
console.log(`${phrases.length} phrases, ${todo.length} to record (${chars} characters)`);
if (dryRun) process.exit(0);

let done = 0;
const failed = [];
async function worker() {
  while (todo.length) {
    const text = todo.shift();
    try {
      const mp3 = await tts(text, { voiceId: VOICE_ID, modelId: MODEL_ID });
      fs.writeFileSync(path.join(AUDIO_DIR, fileFor(text)), mp3);
      process.stdout.write(`\r${++done} recorded`);
    } catch (e) {
      failed.push(text);
      console.error(`\n✗ ${text}: ${e.message}`);
    }
  }
}
await Promise.all(Array.from({ length: CONCURRENCY }, worker));

// Manifest lists only clips that exist, so the game falls back to live TTS for the rest
const clips = {};
phrases.forEach(t => { if (fs.existsSync(path.join(AUDIO_DIR, fileFor(t)))) clips[t] = fileFor(t); });
const used = new Set(Object.values(clips));
fs.readdirSync(AUDIO_DIR).filter(f => f.endsWith('.mp3') && !used.has(f)).forEach(f => fs.unlinkSync(path.join(AUDIO_DIR, f)));
fs.writeFileSync(MANIFEST,
  `// Generated by scripts/gen-nikud-audio.mjs (ElevenLabs ${MODEL_ID}, voice ${VOICE_ID}). Do not edit.\n` +
  `const AUDIO_CLIPS = ${JSON.stringify(clips, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, '\n}')};\n`);
console.log(`\n${Object.keys(clips).length}/${phrases.length} clips in manifest${failed.length ? `, ${failed.length} failed` : ''}`);
